"""Generate the Italian country names of ``qrlab.instruments`` from Unicode CLDR (design 11.5).

Usage, from the repository root:
``uv run python scripts/country_names_it.py tests/data/cldr/it-territories-49.0.0.json``

The input is ``main/it/territories.json`` of the npm package ``cldr-localenames-full``,
version 49.0.0 (Unicode License v3; its notice is ``src/qrlab/instruments/CLDR-LICENSE.txt``).
For every code of :data:`qrlab.instruments.COUNTRIES` the script takes CLDR's Italian name and
its alternative forms (``-alt-short``, ``-alt-variant``), checks that every code has a name and
that no name points to two codes, and writes ``src/qrlab/instruments/_country_names_it.py``.
The CLDR file is read once here; it is not a run-time dependency.
"""

from __future__ import annotations

import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

from qrlab.instruments.countries import normalise_name
from qrlab.instruments.identifiers import COUNTRIES

__all__ = ["OUTPUT", "italian_names", "main", "render"]

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/qrlab/instruments/_country_names_it.py"
VERSION = "49.0.0"


def italian_names(territories: Mapping[str, str]) -> dict[str, tuple[str, ...]]:
    """Return every code's Italian names, the main one first; raise on a gap or a clash."""
    missing = sorted(code for code in COUNTRIES if code not in territories)
    if missing:
        raise ValueError(f"CLDR has no Italian name for {missing}")
    names: dict[str, tuple[str, ...]] = {}
    for code in sorted(COUNTRIES):
        alternatives = sorted(
            value for key, value in territories.items() if key.startswith(f"{code}-alt-")
        )
        found = [territories[code], *alternatives]
        names[code] = tuple(dict.fromkeys(found))
    owner: dict[str, str] = {}
    for code, forms in names.items():
        for form in forms:
            key = normalise_name(form)
            if owner.setdefault(key, code) != code:
                raise ValueError(f"{form!r} names both {owner[key]} and {code}")
    return names


def render(names: Mapping[str, tuple[str, ...]]) -> str:
    """Return the generated module's source."""
    lines = [
        f'"""Italian country names from Unicode CLDR {VERSION} (``main/it/territories.json``).',
        "",
        "Generated by ``scripts/country_names_it.py``: do not edit by hand, re-run the script.",
        "",
        "Copyright © 2001-2026 Unicode, Inc. Data from the Unicode Common Locale Data Repository,",
        "released under the Unicode License v3; the copyright and permission notice is in",
        "``CLDR-LICENSE.txt`` next to this module.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from types import MappingProxyType",
        "",
        "CLDR_VERSION = " + repr(VERSION),
        "",
        "COUNTRY_NAMES_IT: Mapping[str, tuple[str, ...]] = MappingProxyType(",
        "    {",
    ]
    for code, forms in names.items():
        lines.append(f"        {code!r}: {tuple(forms)!r},")
    lines += ["    }", ")", ""]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    """Write the module from the CLDR file given; return 0, or 2 on a wrong call."""
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 1:
        print(__doc__)
        return 2
    data = json.loads(Path(args[0]).read_text(encoding="utf-8"))
    territories = data["main"]["it"]["localeDisplayNames"]["territories"]
    OUTPUT.write_text(render(italian_names(territories)), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":  # pragma: no cover - the command line
    raise SystemExit(main())
