"""Write ``docs/guides/kinds.md`` from the kinds' schemas (design note 12.1).

Usage, from the repository root: ``uv run python scripts/kinds_guide.py``

Every key of every kind is listed with its type, whether it is required, its unit, choices or
range, and its help, at every level of nesting. A test checks that the committed guide equals
this script's output, so the guide cannot drift from the schemas.
"""

from __future__ import annotations

import sys
from collections.abc import Iterator, Sequence
from pathlib import Path

from qrlab.experiments.kinds import KINDS
from qrlab.experiments.registry import ExperimentKind
from qrlab.experiments.schema import Field, FieldKind

__all__ = ["OUTPUT", "guide", "main"]

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/guides/kinds.md"
GENERAL = (
    "portfolio_report", "risk_report", "scenario_analysis", "projection", "optimisation",
    "backtest",
)  # fmt: skip
STUDIES = (
    "study_volatility_managed", "study_one_over_n", "study_factor_zoo", "study_rebalancing",
)  # fmt: skip
INTRO = """# Experiment kinds

<!-- Generated by scripts/kinds_guide.py from the kinds' schemas: do not edit by hand. -->

Each kind turns a config into tables, scalars, figures and sometimes a report. For each kind
this page lists its inputs and every key of its `[parameters]`, at every level, from the
kind's schema (design note 12.1), then the kind's own documentation, from its module.
`qrlab kinds` lists the same kinds, and every kind has a runnable example in
`configs/experiments/` or `configs/studies/`.

The kinds' configs are part of the public API (see {doc}`../compatibility`); the modules that
implement them are not.
"""
STUDIES_INTRO = """## Studies

The four studies of {doc}`../studies/index`. Their configs are in `configs/studies/`; their
data must be downloaded first (see {doc}`reproducing-studies`).
"""


def _detail(spec: Field) -> str:
    parts = []
    if spec.unit:
        parts.append(spec.unit)
    if spec.choices:
        parts.append(", ".join(f"`{c}`" for c in spec.choices))
    bounds = []
    if spec.minimum is not None:
        bounds.append(f"{'>' if spec.open_minimum else '≥'} {spec.minimum:g}")
    if spec.maximum is not None:
        bounds.append(f"{'<' if spec.open_maximum else '≤'} {spec.maximum:g}")
    if bounds:
        parts.append(" and ".join(bounds))
    if spec.kind is FieldKind.MAP and spec.key_kind is not None:
        parts.append(f"keys: {spec.key_kind.value}")
    if spec.allow_empty:
        parts.append("may be empty")
    return "; ".join(parts)


def _kind_name(spec: Field) -> str:
    if spec.kind is FieldKind.LIST and spec.item is not None:
        return f"list of {spec.item.kind.value}"
    if spec.kind is FieldKind.MAP and spec.item is not None:
        return f"map of {spec.item.kind.value}"
    return spec.kind.value


def _rows(fields: Sequence[Field], prefix: str) -> Iterator[str]:
    for spec in fields:
        path = f"{prefix}{spec.key}"
        required = "yes" if spec.required else "no"
        help_text = spec.help.en.replace("|", "\\|")
        yield f"| `{path}` | {_kind_name(spec)} | {required} | {_detail(spec)} | {help_text} |"
        yield from _inner(spec, path)


def _inner(spec: Field, path: str) -> Iterator[str]:
    if spec.kind in (FieldKind.TABLE, FieldKind.RECORDS):
        marker = "[]" if spec.kind is FieldKind.RECORDS else ""
        yield from _rows(spec.fields, f"{path}{marker}.")
    elif spec.kind is FieldKind.MAP and spec.item is not None:
        yield from _inner(spec.item, f"{path}.<key>")
    elif spec.kind is FieldKind.VARIANT and spec.selector is not None:
        options = ", ".join(f"`{o}`" for o in spec.variants)
        yield f"| `{path}.{spec.selector}` | choice | yes | {options} | Selects the fields below. |"
        for option, fields in spec.variants.items():
            yield from _rows(fields, f"{path}({spec.selector} = {option}).")


def _section(kind: ExperimentKind) -> str:
    schema = kind.schema
    if schema is None:
        raise ValueError(f"{kind.name} has no schema")
    lines = [f"### `{kind.name}`", "", f"*{kind.description}.*", "", "**Inputs**", ""]
    for spec in schema.inputs:
        status = "a group of files, one per key" if spec.group else (
            "required" if spec.required else "optional"
        )  # fmt: skip
        lines.append(f"- `{spec.name}` ({status}): {spec.help.en}")
    if not schema.inputs:
        lines.append("- none")
    lines += [
        "",
        "**Parameters**",
        "",
        "| Key | Type | Required | Unit, choices or range | Meaning |",
        "|---|---|---|---|---|",
        *_rows(schema.parameters, ""),
        "",
        f"Seed: {'required' if kind.needs_seed else 'not used'}.",
        "",
        "```{eval-rst}",
        f".. automodule:: {kind.run.__module__}",
        "   :no-members:",
        "   :no-index:",
        "```",
        "",
    ]
    return "\n".join(lines)


def guide() -> str:
    """Return the guide's text."""
    missing = sorted(set(KINDS) - set(GENERAL) - set(STUDIES))
    if missing:
        raise ValueError(f"kinds without a section: {missing}")
    parts = [INTRO, "## General analyses\n"]
    parts += [_section(KINDS[name]) for name in GENERAL]
    parts.append(STUDIES_INTRO)
    parts += [_section(KINDS[name]) for name in STUDIES]
    return "\n".join(parts).rstrip("\n") + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """Write the guide; return 0, or 2 when called with arguments."""
    args = list(sys.argv[1:] if argv is None else argv)
    if args:
        print(__doc__)
        return 2
    OUTPUT.write_text(guide(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":  # pragma: no cover - the command line
    raise SystemExit(main())
