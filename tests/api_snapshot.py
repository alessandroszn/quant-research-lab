"""A text listing of qrlab's public API, compared with ``docs/api/public-api.txt`` by a test.

Public means every name in the ``__all__`` of ``qrlab``'s subpackages, plus the modules in
:data:`ALSO_PUBLIC` (design note 6.3a). ``qrlab.studies`` declares no ``__all__``: the studies
are reproduced through their experiment kinds, whose configs are public, not by importing them.
Each line gives the qualified name, its kind and its signature; classes also list their public
methods, properties and attributes defined in qrlab, and enums list their members. Simple
constants show their value; other objects show only their type.

Regenerate the file after a deliberate change of the public API::

    uv run python tests/api_snapshot.py --write
"""

from __future__ import annotations

import enum
import importlib
import inspect
import pkgutil
import sys
from collections.abc import Callable, Iterable
from pathlib import Path
from types import ModuleType

__all__ = ["ALSO_PUBLIC", "SNAPSHOT", "describe", "listing", "public_modules"]

ALSO_PUBLIC = ("qrlab.experiments.kinds", "qrlab.experiments.workspace")
"""Deeper modules that are public: ``KINDS`` is what ``run_experiment`` needs."""

SNAPSHOT = Path(__file__).parents[1] / "docs" / "api" / "public-api.txt"
HEADER = (
    "# The public API of qrlab (design note 6.3a). Generated by tests/api_snapshot.py;\n"
    "# a change here is a change of the public API and must be deliberate.\n"
)
_SIMPLE = (bool, int, float, str, type(None))


def public_modules(package: str = "qrlab", also: Iterable[str] = ALSO_PUBLIC) -> list[ModuleType]:
    """Return the package's subpackages that declare ``__all__``, plus ``also``, by name."""
    root = importlib.import_module(package)
    modules = [importlib.import_module(name) for name in also]
    for info in pkgutil.iter_modules(root.__path__, prefix=f"{package}."):
        if info.name.rsplit(".", 1)[1].startswith("_"):
            continue
        module = importlib.import_module(info.name)
        if hasattr(module, "__all__"):
            modules.append(module)
    return sorted(modules, key=lambda m: m.__name__)


def _signature(func: Callable[..., object], *, drop_first: bool = False) -> str:
    try:
        signature = inspect.signature(func)
    except (TypeError, ValueError):
        return "(...)"
    params = list(signature.parameters.values())
    if drop_first and params:
        params = params[1:]
    return str(signature.replace(parameters=params))


def _value(obj: object) -> str:
    if isinstance(obj, enum.Enum):
        return f"{type(obj).__name__}.{obj.name}"
    if isinstance(obj, _SIMPLE):
        return f"{type(obj).__name__} = {obj!r}"
    if isinstance(obj, (tuple, frozenset)) and all(isinstance(x, _SIMPLE) for x in obj):
        items = sorted(obj, key=repr) if isinstance(obj, frozenset) else list(obj)
        return f"{type(obj).__name__} = {items!r}"
    return type(obj).__name__


def _defined_in_qrlab(cls: type, name: str) -> object | None:
    for klass in cls.__mro__:
        if name in vars(klass):
            return vars(klass)[name] if klass.__module__.startswith("qrlab") else None
    return None


def _class_lines(qualified: str, cls: type) -> list[str]:
    if issubclass(cls, enum.Enum):
        lines = [f"{qualified}  enum"]
        lines += [f"{qualified}.{m.name}  member = {m.value!r}" for m in cls]
        return lines
    init = _defined_in_qrlab(cls, "__init__")
    head = _signature(init, drop_first=True) if callable(init) else "(inherited)"
    kind = "exception" if issubclass(cls, BaseException) else "class"
    lines = [f"{qualified}  {kind}{head}"]
    for name in sorted(dir(cls)):
        if name.startswith("_"):
            continue
        attr = _defined_in_qrlab(cls, name)
        if attr is None:
            continue
        if isinstance(attr, property):
            lines.append(f"{qualified}.{name}  property")
        elif isinstance(attr, classmethod):
            lines.append(
                f"{qualified}.{name}  classmethod{_signature(attr.__func__, drop_first=True)}"
            )
        elif isinstance(attr, staticmethod):
            lines.append(f"{qualified}.{name}  staticmethod{_signature(attr.__func__)}")
        elif inspect.isfunction(attr):
            lines.append(f"{qualified}.{name}  method{_signature(attr, drop_first=True)}")
        else:
            lines.append(f"{qualified}.{name}  attribute {_value(attr)}")
    return lines


def describe(module: ModuleType) -> list[str]:
    """Return the lines for every name in ``module.__all__``, sorted by name."""
    lines = []
    for name in sorted(module.__all__):
        obj = getattr(module, name)
        qualified = f"{module.__name__}.{name}"
        if inspect.isclass(obj):
            lines += _class_lines(qualified, obj)
        elif inspect.isfunction(obj):
            lines.append(f"{qualified}  function{_signature(obj)}")
        elif inspect.ismodule(obj):
            lines.append(f"{qualified}  module")
        else:
            lines.append(f"{qualified}  constant {_value(obj)}")
    return lines


def listing(modules: Iterable[ModuleType] | None = None) -> str:
    """Return the full listing, with its header."""
    lines = [line for m in (modules or public_modules()) for line in describe(m)]
    return HEADER + "\n".join(lines) + "\n"


if __name__ == "__main__":  # pragma: no cover - a maintenance command
    if sys.argv[1:] != ["--write"]:
        raise SystemExit("usage: python tests/api_snapshot.py --write")
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.write_text(listing(), encoding="utf-8", newline="\n")
    print(f"wrote {SNAPSHOT}")
