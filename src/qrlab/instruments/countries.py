def normalise_name(text: str) -> str:
    """Return ``text`` without accents, in lower case, with single spaces (for matching)."""
    decomposed = unicodedata.normalize("NFKD", text)
    plain = "".join(c for c in decomposed if not unicodedata.combining(c))
    return " ".join(plain.casefold().split())


_BY_NAME: Mapping[str, str] = MappingProxyType(
    {
        **{normalise_name(name): code for code, name in COUNTRY_NAMES.items()},
        **{normalise_name(alias): code for alias, code in COUNTRY_ALIASES.items()},
    }
)


def country_code(name: str) -> str:
    """Return the ISO 3166-1 alpha-2 code of a country name, or raise.

    Raises
    ------
    ValidationError
        If the name is neither an ISO short name nor a listed alias. Declare the file's own
        wording in the holdings mapping's ``country_values`` instead.
    """
    code = _BY_NAME.get(normalise_name(name))
    if code is None:
        raise ValidationError(
            f"unknown country name {name!r}: add it to the mapping's country_values"
        )
    return code
